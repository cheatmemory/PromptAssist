/** 按交付形态过滤：这些形态不需要响应式/触达目标，那部分是噪音。 */
const DELIVERABLE_UI_SCOPE = {
  web: ['responsive', 'a11y'],
  desktop: ['a11y', 'components'],
  mobile: ['responsive', 'a11y', 'density'],
  miniapp: ['responsive', 'a11y', 'density'],
  cli: ['density'],
  api: ['density', 'feedback'],
  unspecified: ['responsive', 'a11y'],
}

/**
 * 从段②答案里推断用户选定的界面形态。
 * 与 `matchProfile` 同理：**按最长命中关键词打分**，不按数组顺序——
 * 顺序匹配会被短词劫持（'app' 抢走「小程序」这类问题在实测里出现过）。
 * 命中 0 个时返回空数组，渲染时会给出四形态共性提示而不是瞎猜。
 */
const UI_FORM_KEYWORDS = {
  conversational: ['对话', '聊天', '追问', '问答', '自然语言', 'chat', 'conversational'],
  form: ['表单', '填写', '录入', '上传', '参数', '材料', 'form'],
  dashboard: ['看板', '仪表盘', '仪表板', '图表', '概览', '总览', '监控', 'dashboard', 'kanban'],
  'card-list': ['卡片', '列表', '明细', '清单', 'card', 'list'],
}

export function matchUIForms(answers) {
  const text = Object.values(answers || {})
    .flatMap(v => (Array.isArray(v) ? v : [v]))
    .filter(v => typeof v === 'string')
    .join(' ')
    .toLowerCase()
  if (!text.trim()) return []
  const hit = []
  for (const [id, keys] of Object.entries(UI_FORM_KEYWORDS)) {
    for (const k of keys) {
      if (text.includes(k.toLowerCase())) { hit.push(id); break }
    }
  }
  return hit
}

/**
 * 渲染可内联进 meta-prompt 的 UI 标准文本。
 * @param {object} opts
 * @param {string} opts.deliverable 交付形态 id，用于过滤无关维度
 * @param {string[]} opts.uiForms  用户在段②选定的界面形态 id 列表
 * @returns {string}
 */
export function renderUIStandards({ deliverable = 'unspecified', uiForms = [] } = {}) {
  const scope = DELIVERABLE_UI_SCOPE[deliverable] || DELIVERABLE_UI_SCOPE.unspecified
  const lines = []

  lines.push('## 界面设计规范（硬约束，不是建议）')
  lines.push('')
  lines.push('以下每一条都是**可被逐条断言的阈值**。违反任意一条，本次生成的界面即为不合格。')
  lines.push('')

  lines.push('### A. 一票否决项（命中任意一条即不合格）')
  HARD_FAILS.forEach((f, i) => lines.push(`${i + 1}. ${f}`))
  lines.push('')

  lines.push('### B. 通用规则')
  const titles = {
    hierarchy: '视觉层级',
    spacing: '留白与间距',
    color: '配色与对比度',
    typography: '字体规范',
    components: '组件一致性',
    density: '信息密度',
    feedback: '操作反馈与错误提示',
    responsive: '响应式',
    a11y: '无障碍',
  }
  for (const key of Object.keys(titles)) {
    if (!scope.includes(key)) continue
    lines.push(`**${titles[key]}**`)
    ASSERTIVE_RULES[key].forEach(r => lines.push(`- ${r}`))
    if (key === 'color') lines.push(`- 对比度阈值（WCAG 2.2 AA）：正文 ${CONTRAST.bodyText}；大字 ${CONTRAST.largeText}；非文本组件 ${CONTRAST.nonText}；焦点环 ${CONTRAST.focusRing}。${CONTRAST.reference}`)
    lines.push('')
  }

  lines.push('### C. 界面形态适配')
  lines.push('')
  const chosen = uiForms.length ? UI_FORM_PROFILES.filter(p => uiForms.includes(p.id)) : []
  if (!uiForms.length) {
    // 未选形态时**不要**把四份全渲染出来——那会让 prompt 膨胀 4 倍且互相矛盾
    // （对话式禁止侧栏、看板式要求侧栏）。给共性原则，让模型按任务自行取舍。
    lines.push('（用户未指定界面形态。按以下共性执行，具体形态的细则自行取舍，不要机械套用某一形态：）')
    lines.push('- 单一信息层级：任何时刻只有一个视觉主角，其余退到二三级')
    lines.push('- 默认折叠：支撑细节与原始数据不进主流程')
    lines.push('- 关键动作唯一入口：同一功能不得有两处入口')
    lines.push('- 当前待用户决策的那个动作，必须是当屏唯一的主按钮')
    lines.push('- 多步流程显示进度（当前第几步 / 共几步）')
    lines.push('')
    lines.push('混合形态参考（现实中最常见的组合，把每种形态放进各自该在的位置，**不要互相嵌套**）：')
    HYBRID_LAYOUT.forEach(l => lines.push(`- ${l}`))
    lines.push('')
  } else if (uiForms.length >= 3) {
    // 三种及以上 = 现实中的混合形态。给分层骨架而不是三份细则叠加——
    // 叠加会让「侧栏到底能不能加」这类冲突规则同时出现。
    lines.push(`（用户选定了多种界面形态：${chosen.map(p => p.label).join(' + ')}。采用**混合分层布局**，不要把各形态细则叠加使用——它们会互相矛盾）：`)
    HYBRID_LAYOUT.forEach(l => lines.push(`- ${l}`))
    lines.push('')
    lines.push('各形态最关键的 3 条：')
    for (const p of chosen) {
      lines.push(`- **${p.label}**：${p.forbid[0]}；${p.layout[0]}`)
    }
    lines.push('')
  } else {
    for (const p of chosen) {
      lines.push(`#### ${p.label}（${p.when}）`)
      lines.push('布局结构：')
      p.layout.forEach(l => lines.push(`- ${l}`))
      lines.push('交互范式：')
      p.interaction.forEach(l => lines.push(`- ${l}`))
      if (p.chartRules) {
        lines.push('图表选型：')
        p.chartRules.forEach(l => lines.push(`- ${l}`))
      }
      if (p.errorTemplates) {
        lines.push('错误提示句式模板（照此风格写）：')
        p.errorTemplates.forEach(t => lines.push(`- 「${t}」`))
      }
      lines.push('必须做到：')
      p.must.forEach(l => lines.push(`- ${l}`))
      lines.push('禁止：')
      p.forbid.forEach(l => lines.push(`- ${l}`))
      lines.push('')
    }
  }

  return lines.join('\n')
}

